"""
Builds lib/places-data.ts: every US city, town and census-designated place with the point at its centre and its population, for the
search box's city fallback. Sources (both official, public): the Census 2024 Gazetteer place file (names, internal points) and the
Census Vintage 2024 city population estimates (incorporated places only; a CDP has no estimate and sorts last).

  curl -LO https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_place_national.zip && unzip 2024_Gaz_place_national.zip
  curl -L -o sub-est2024.csv https://www2.census.gov/programs-surveys/popest/datasets/2020-2024/cities/totals/sub-est2024.csv
  python3 scripts/build-places.py 2024_Gaz_place_national.txt sub-est2024.csv
"""
import csv, json, re, sys

gaz_path, pop_path = sys.argv[1], sys.argv[2]
pop = {}
with open(pop_path, encoding="latin-1") as f:
    for row in csv.DictReader(f):
        if row["SUMLEV"] == "162":
            pop[row["STATE"] + row["PLACE"]] = int(row["POPESTIMATE2024"] or 0)

rows = []
with open(gaz_path, encoding="utf-8") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        row = {k.strip(): v.strip() for k, v in row.items()}
        raw = row["NAME"].replace(" (balance)", "")
        # "Fort Myers city" -> "Fort Myers"; "Nashville-Davidson metropolitan government" -> "Nashville-Davidson".
        name = re.sub(r"( [a-z][a-z/ ]*)+$", "", re.sub(r" CDP$", "", raw)).strip()
        if not name or "|" in name:
            continue
        lat, lon = float(row["INTPTLAT"]), float(row["INTPTLONG"])
        p = pop.get(row["GEOID"], 0)
        rows.append((name, row["USPS"], lat, lon, p))
        # The Census calls Honolulu "Urban Honolulu".
        if name.startswith("Urban "):
            rows.append((name[6:], row["USPS"], lat, lon, p))
        # A consolidated city is also found by its first part ("Nashville", "Louisville", "Augusta", "Athens").
        if raw != name + " city" and re.search(r"(government|county|metro)", raw[len(name):]):
            alias = re.split(r"[-/]", name)[0].strip()
            if alias and alias != name:
                rows.append((alias, row["USPS"], lat, lon, p))

lines = "\n".join(f"{n}|{s}|{la:.4f}|{lo:.4f}|{p}" for n, s, la, lo, p in rows)
with open("lib/places-data.ts", "w", encoding="utf-8") as out:
    out.write("// Generated by scripts/build-places.py from the Census 2024 Gazetteer and Vintage 2024 population estimates. Do not edit.\n")
    out.write("// One place per line: name|state|lat|lon|population (0 when the Census has no estimate, as for a census-designated place).\n")
    out.write("export const PLACES_DATA = " + json.dumps(lines, ensure_ascii=False) + ";\n")
print(len(rows), "places")
