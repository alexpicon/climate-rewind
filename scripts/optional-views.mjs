// Writes the two files that let the app show "What's changing here" (future) and "Get ready" (ready) only when their view files exist:
//   lib/ui/optional-tabs.generated.ts          which of the two tab ids are available (no component imports; the tab list reads it)
//   components/views/optional-views.generated.ts  a static import of each view that exists (a bundler needs static imports)
// A missing file is simply left out, so the build never breaks on it. Runs before `next dev` and `next build`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const VIEWS = [
  { tab: "future", name: "FutureView", file: "components/views/future/FutureView.tsx" },
  { tab: "ready", name: "ReadyView", file: "components/views/ready/ReadyView.tsx" },
];

const found = VIEWS.filter((view) => {
  const full = path.join(root, view.file);
  if (!existsSync(full)) return false;
  // Named export, as the rest of the app does it. A file that exports something else is skipped, not imported.
  const source = readFileSync(full, "utf8");
  const exported = new RegExp(`export\\s+(?:async\\s+)?(?:function|const|class)\\s+${view.name}\\b|export\\s*\\{[^}]*\\b${view.name}\\b`).test(source);
  if (!exported) console.warn(`optional-views: ${view.file} exists but does not export ${view.name}; the "${view.tab}" tab stays hidden.`);
  return exported;
});

const banner = "// Generated by scripts/optional-views.mjs. Do not edit by hand.\n";

const tabsFile = `${banner}export const AVAILABLE_OPTIONAL_TABS: readonly ("future" | "ready")[] = [${found.map((v) => `"${v.tab}"`).join(", ")}];\n`;

const viewsFile =
  `${banner}import type { ComponentType } from "react";\nimport type { LookupPayload } from "@/lib/types";\n` +
  found.map((v) => `import { ${v.name} } from "@/${v.file.replace(/\.tsx$/, "")}";`).join("\n") +
  `${found.length ? "\n" : ""}\nexport const OPTIONAL_VIEWS: Partial<Record<"future" | "ready", ComponentType<{ data: LookupPayload }>>> = {${found.map((v) => ` ${v.tab}: ${v.name},`).join("")} };\n`;

const write = (rel, text) => {
  const full = path.join(root, rel);
  if (!existsSync(full) || readFileSync(full, "utf8") !== text) writeFileSync(full, text);
};
write("lib/ui/optional-tabs.generated.ts", tabsFile);
write("components/views/optional-views.generated.ts", viewsFile);
console.log(`optional-views: ${found.length ? found.map((v) => v.tab).join(", ") : "none"} available`);
